import streamlit as st
from Prediction_Helper import predict

# ==========================================
# 1. PAGE CONFIGURATION & CUSTOM CSS
# ==========================================
st.set_page_config(page_title="Health Insurance Predictor", page_icon="🏥", layout="wide")

st.markdown("""
    <style>
    .main { background-color: #f8f9fa; }
    .stButton>button {
        width: 100%; background-color: #007bff; color: white;
        font-size: 18px; font-weight: bold; padding: 10px;
        border-radius: 8px; transition: 0.3s;
    }
    .stButton>button:hover { background-color: #0056b3; color: white; }
    .stAlert { border-radius: 10px; }
    </style>
""", unsafe_allow_html=True)

# ==========================================
# 2. HEADER
# ==========================================
st.title("🏥 Health Insurance Cost Predictor")
st.markdown("Enter your details below to get an estimated annual health insurance premium.")
st.divider()

# ==========================================
# 3. CATEGORICAL OPTIONS
# ==========================================
categorical_options = {
    'Gender': ['Male', 'Female'],
    'Marital Status': ['Unmarried', 'Married'],
    'BMI Category': ['Normal', 'Obesity', 'Overweight', 'Underweight'],
    'Smoking Status': ['No Smoking', 'Regular', 'Occasional'],
    'Employment Status': ['Salaried', 'Self-Employed', 'Freelancer'], 
    'Region': ['Northwest', 'Southeast', 'Northeast', 'Southwest'],
    'Medical History': [
        'No Disease', 'Diabetes', 'High blood pressure', 'Diabetes & High blood pressure',
        'Thyroid', 'Heart disease', 'High blood pressure & Heart disease', 'Diabetes & Thyroid',
        'Diabetes & Heart disease'
    ],
    'Insurance Plan': ['Bronze', 'Silver', 'Gold']
}

# ==========================================
# 4. INPUT FORM
# ==========================================
with st.form(key='insurance_form'):
    
    st.subheader("👤 Personal Details")
    col1, col2, col3 = st.columns(3)
    with col1:
        age = st.number_input('Age', min_value=18, step=1, max_value=100, value=30)
    with col2:
        gender = st.selectbox('Gender', categorical_options['Gender'])
    with col3:
        marital_status = st.selectbox('Marital Status', categorical_options['Marital Status'])

    st.divider()

    st.subheader("💰 Financial & Plan Details")
    col4, col5, col6 = st.columns(3)
    with col4:
        income_lakhs = st.number_input('Annual Income (in Lakhs)', step=1.0, min_value=0.0, max_value=200.0, value=10.0)
    with col5:
        employment_status = st.selectbox('Employment Status', categorical_options['Employment Status'])
    with col6:
        insurance_plan = st.selectbox('Insurance Plan', categorical_options['Insurance Plan'])

    st.divider()

    st.subheader("🩺 Health & Lifestyle")
    col7, col8, col9 = st.columns(3)
    with col7:
        bmi_category = st.selectbox('BMI Category', categorical_options['BMI Category'])
    with col8:
        smoking_status = st.selectbox('Smoking Status', categorical_options['Smoking Status'])
    with col9:
        region = st.selectbox('Region', categorical_options['Region'])
        
    col10, col11 = st.columns(2)
    with col10:
        medical_history = st.selectbox('Medical History', categorical_options['Medical History'])
    with col11:
        number_of_dependants = st.number_input('Number of Dependants', min_value=0, step=1, max_value=20, value=0)

    submit_button = st.form_submit_button(label='Calculate Estimated Premium')

# ==========================================
# 5. PREDICTION LOGIC
# ==========================================
if submit_button:
    input_dict = {
        'Age': age,
        'Number of Dependants': number_of_dependants,
        'Income in Lakhs': income_lakhs,
        'Insurance Plan': insurance_plan,
        'Employment Status': employment_status,
        'Gender': gender,
        'Marital Status': marital_status,
        'BMI Category': bmi_category,
        'Smoking Status': smoking_status,
        'Region': region,
        'Medical History': medical_history
    }

    with st.spinner('Calculating your premium...'):
        try:
            prediction = predict(input_dict)
            
            st.success("Prediction Successful!")
            st.metric(label="Estimated Annual Premium", value=f"₹ {prediction:,}")
            
            st.info("ℹ️ Note: This is an estimated value generated by a Machine Learning model and should not be considered a final quote.")
            
        except Exception as e:
            st.error(f"An error occurred during prediction: {e}")